#!/usr/bin/env node
// Snapshots content from the package root into src/lib/generated/ (gitignored) so the site stays in step
// with the code without copying prose: the package version and the verified Paseo release, the changelog,
// and the source files the recipes show. Sources are highlighted here, so Prism stays out of the browser
// bundle. Runs as predev and prebuild.
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { highlight } from './highlight.js';

const site = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const root = resolve(site, '..');
const out = resolve(site, 'src/lib/generated');
mkdirSync(out, { recursive: true });

const read = (path) => readFileSync(resolve(root, path), 'utf8');
const write = (name, text) => {
  writeFileSync(join(out, name), text);
  console.log(`[sync-content] src/lib/generated/${name}`);
};

// Version, Node range and the Paseo release ppd was verified on.
const pkg = JSON.parse(read('package.json'));
const verifiedPaseo = read('src/compat.ts').match(/VERIFIED_PASEO = "([^"]+)"/)?.[1];
if (!verifiedPaseo) throw new Error('VERIFIED_PASEO not found in src/compat.ts');
const meta = { version: pkg.version, node: pkg.engines.node, verifiedPaseo, license: pkg.license };
write('meta.js', `// Generated by scripts/sync-content.mjs.\nexport const meta = ${JSON.stringify(meta, null, 2)};\n`);

// CHANGELOG.md as an mdsvex component, minus its own title. Braces outside code fences would be read as
// Svelte expressions, so they are escaped.
let fenced = false;
const changelog = read('CHANGELOG.md')
  .replace(/^# Changelog\n+/, '')
  .split('\n')
  .map((line) => {
    if (line.startsWith('```')) fenced = !fenced;
    return fenced || line.startsWith('```') ? line : line.replaceAll('{', '&#123;').replaceAll('}', '&#125;');
  })
  .join('\n');
write('changelog.svx', changelog);

// Source files shown on the recipe pages: the agent-hook template and the recipe plugins in recipes/.
const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (name === 'node_modules' || name.startsWith('.')) return [];
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
const LANGS = { '.ts': 'ts', '.tsx': 'tsx', '.json': 'json', '.mjs': 'js', '.js': 'js', '.md': 'markdown', '.yml': 'yaml' };
const files = [
  ...['index.server.ts', 'index.client.tsx', 'shared/turn-summary.ts', 'server/summarize.ts', 'client/summary-card.tsx'].map(
    (file) => ({ repoPath: `templates/agent-hook/${file}`, label: file })
  ),
  ...walk(resolve(site, 'recipes')).map((path) => {
    const repoPath = relative(root, path);
    return { repoPath, label: repoPath.split('/').slice(3).join('/') };
  })
];
const sources = {};
for (const { repoPath, label } of files) {
  if (!existsSync(resolve(root, repoPath))) throw new Error(`missing source: ${repoPath}`);
  const code = read(repoPath).replace(/\n$/, '');
  sources[repoPath] = { label, html: highlight(code, LANGS[extname(repoPath)] ?? 'plain') };
}
write('sources.js', `// Generated by scripts/sync-content.mjs.\nexport const sources = ${JSON.stringify(sources, null, 2)};\n`);
console.log(`[sync-content] ${Object.keys(sources).length} source files, version ${meta.version}, Paseo ${verifiedPaseo}`);
